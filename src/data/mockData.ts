export function createDefaultCopies(
  bookId: string,
  prefix: string,
  totalCopies: number,
  availableCopies: number,
  shelfLocation: string,
  borrowers?: { copyNum: number; studentId: string; txId: string }[]
): BookCopy[] {
  const copies: BookCopy[] = [];
  const parts = shelfLocation.split("→").map((s) => s.trim());
  const building = parts[0] || "Block A";
  const floor = parts[1] || "Floor 1";
  const rack = parts[2] || "Rack A1";
  const shelf = parts[3] || "Shelf 1";

  for (let i = 1; i <= totalCopies; i++) {
    const copyId = `LIB-${prefix}-${String(i).padStart(4, "0")}`;
    const activeBorrow = borrowers?.find((b) => b.copyNum === i);
    const position = `Position ${String(i).padStart(2, "0")}`;
    const fullShelfLocation = `${building} → ${floor} → ${rack} → ${shelf} → ${position}`;

    let status: CopyStatus = "available";
    let condition: CopyCondition = "good";
    let studentId: string | null = null;
    let txId: string | null = null;

    if (activeBorrow) {
      status = "issued";
      studentId = activeBorrow.studentId;
      txId = activeBorrow.txId;
      condition = i % 2 === 0 ? "good" : "fair";
    } else if (i > availableCopies) {
      if (i === totalCopies && totalCopies > 4) {
        status = "maintenance";
        condition = "damaged";
      } else if (i === totalCopies - 1 && totalCopies > 5) {
        status = "reserved";
        condition = "good";
      } else {
        status = "issued";
        studentId = "BCA-2024-015";
        condition = "good";
      }
    } else {
      status = "available";
      condition = i === 1 ? "new" : i === 2 ? "good" : "fair";
    }

    copies.push({
      id: copyId,
      bookId,
      copyNumber: i,
      barcode: copyId,
      qrCode: copyId,
      status,
      condition,
      shelfLocation: fullShelfLocation,
      building,
      floor,
      rack,
      shelf,
      position,
      currentBorrowerStudentId: studentId,
      currentTransactionId: txId,
      addedDate: "2024-01-15",
      lastInspectedDate: "2026-08-15",
      notes: condition === "new" ? "Mint condition" : condition === "damaged" ? "Minor spine wear" : "Regular copy",
    });
  }
  return copies;
}

